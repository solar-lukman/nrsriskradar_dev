#!/usr/bin/env node
/**
 * UAT traceability generator.
 *
 * Parses the case IDs declared in docs/uat-test-plan.md and the `uat`
 * annotations declared in the Playwright specs, then emits a coverage matrix
 * to docs/uat-traceability.md.
 *
 * Exit codes:
 *   0  every annotation maps to a plan case (or is an allowed extra)
 *   1  one or more orphan annotations were found (spec claims a case ID that
 *      does not exist in the plan) — CI should fail on this
 *
 * Pass --strict to also fail when any P1 plan case has no automation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PLAN = path.join(root, 'docs/uat-test-plan.md');
const SPEC_DIR = path.join(root, 'e2e/tests');
const OUT = path.join(root, 'docs/uat-traceability.md');

/** Annotations that intentionally have no plan case (security depth / negatives). */
const ALLOWED_EXTRA = /^UAT-(RLS-[A-Z0-9]+|DATA-neg)$|-(neg|extra-[a-z-]+)$/;

function readPlanCases() {
  const md = fs.readFileSync(PLAN, 'utf8');
  const cases = new Map();
  for (const line of md.split('\n')) {
    const m = line.match(/^\|\s*(UAT-[A-Z]+-\d+)\s*\|\s*(P\d)\s*\|\s*([^|]*)\|\s*([^|]*)\|/);
    if (m) {
      cases.set(m[1], {
        id: m[1],
        priority: m[2],
        role: m[3].trim(),
        step: m[4].trim(),
      });
    }
  }
  return cases;
}

function readAnnotations() {
  const map = new Map(); // id -> [{file, title}]
  for (const file of fs.readdirSync(SPEC_DIR).filter((f) => f.endsWith('.spec.ts'))) {
    const src = fs.readFileSync(path.join(SPEC_DIR, file), 'utf8');
    const lines = src.split('\n');
    let currentTitle = '';
    for (const line of lines) {
      const t = line.match(/^\s*test\((?:`|')(.+?)(?:`|')\s*,/);
      if (t) currentTitle = t[1];
      const a = line.match(/type:\s*'uat',\s*description:\s*'([^']+)'/);
      if (a) {
        if (!map.has(a[1])) map.set(a[1], []);
        map.get(a[1]).push({ file, title: currentTitle });
      }
    }
  }
  return map;
}

const plan = readPlanCases();
const annotations = readAnnotations();

const covered = [...plan.keys()].filter((id) => annotations.has(id));
const missing = [...plan.values()].filter((c) => !annotations.has(c.id));
const orphans = [...annotations.keys()].filter((id) => !plan.has(id) && !ALLOWED_EXTRA.test(id));
const extras = [...annotations.keys()].filter((id) => !plan.has(id) && ALLOWED_EXTRA.test(id));

const pct = plan.size ? Math.round((covered.length / plan.size) * 1000) / 10 : 0;

const rows = [...plan.values()].map((c) => {
  const hits = annotations.get(c.id) || [];
  return `| ${c.id} | ${c.priority} | ${c.role} | ${hits.length ? 'Automated' : 'Manual only'} | ${
    hits.map((h) => `\`${h.file}\``).join('<br>') || '—'
  } |`;
});

const md = `# UAT traceability matrix

Generated by \`node scripts/uat-traceability.mjs\` — do not edit by hand.

- Plan cases: **${plan.size}**
- Automated: **${covered.length}** (${pct}%)
- Manual only: **${missing.length}**
- Extra automated checks with no plan case: **${extras.length}**
- Orphan annotations (spec IDs absent from the plan): **${orphans.length}**

## Case coverage

| Case | Priority | Role | Automation | Spec |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

## Extra automated checks (security depth / negative paths)

${extras.length ? extras.map((id) => `- \`${id}\` — ${(annotations.get(id) || []).map((h) => h.file).join(', ')}`).join('\n') : '_none_'}

${orphans.length ? `## Orphan annotations (fix these)\n\n${orphans.map((id) => `- \`${id}\``).join('\n')}\n` : ''}`;

fs.writeFileSync(OUT, md);

console.log(`UAT traceability: ${covered.length}/${plan.size} plan cases automated (${pct}%).`);
if (extras.length) console.log(`Extra checks: ${extras.length}`);
if (missing.length) {
  console.log('Manual-only cases:');
  for (const c of missing) console.log(`  ${c.id} [${c.priority}] ${c.step}`);
}
if (orphans.length) {
  console.error('\nOrphan annotations not present in docs/uat-test-plan.md:');
  for (const id of orphans) console.error(`  ${id}`);
  process.exit(1);
}
if (process.argv.includes('--strict')) {
  const p1 = missing.filter((c) => c.priority === 'P1');
  if (p1.length) {
    console.error(`\n--strict: ${p1.length} P1 case(s) have no automation.`);
    process.exit(1);
  }
}
